/* -------------------------------------------------------------------------- */
/* 2. Normalisation + id helpers                                             */
/* -------------------------------------------------------------------------- */

// Match the app's runtime normaliser EXACTLY (normalizeArabicForAudio in
// index.html): NFC, strip tatweel (U+0640) + bidi control marks
// (U+200E/200F, U+202A-202E, U+2066-2069), trim, collapse internal
// whitespace. Harakāt / shaddah / sukūn are DELIBERATELY kept — بَ and بِ
// are different sounds and must map to different recordings.
const TATWEEL_AND_BIDI = /[ـ‎‏‪-‮⁦-⁩]/g;
function normalizeArabic(s) {
    return String(s == null ? "" : s)
        .normalize("NFC")
        .replace(TATWEEL_AND_BIDI, "")
        .trim()
        .replace(/\s+/g, " ");
}

// Filenames are built from each item's stable data id (e.g. words/sch-06.mp3),
// never from transliteration — transliterations collide (sabʿah / ṣabāḥ → "sabah").

/* -------------------------------------------------------------------------- */
/* 3. Build the target list from the data                                    */
/* -------------------------------------------------------------------------- */
function buildTargets(data) {
    const targets = [];
    const byKey = new Map(); // normalizedArabic -> first target that claimed it

    const byId = new Map();

    /* push an audio target.
       - if t.aliasOf is set, it's an explicit alias (e.g. an M9 reduced/
         unvowelled sentence that shares the base sentence's recording);
       - otherwise, if the exact normalised Arabic string was already claimed
         by an earlier target, it becomes an alias of that one;
       - otherwise it's a distinct recording. */
    function push(t) {
        t.key = normalizeArabic(t.arabic);

        if (t.aliasOf) {
            const base = byId.get(t.aliasOf);
            if (!base) throw new Error(`alias ${t.id} references unknown base ${t.aliasOf}`);
            Object.assign(t, { role: "alias", file: base.file, nativeTarget: base.nativeTarget });
            byId.set(t.id, t);
            targets.push(t);
            return;
        }

        const existing = byKey.get(t.key);
        if (existing) {
            Object.assign(t, { role: "alias", aliasOf: existing.id, file: existing.file, nativeTarget: existing.nativeTarget });
            byId.set(t.id, t);
            targets.push(t);
            return;
        }

        t.role = t.role || "recording";
        byKey.set(t.key, t);
        byId.set(t.id, t);
        targets.push(t);
    }

    const A = data.arabicAlphabet;

    // 3.1 letters (isolated) + letter names — Tier 1
    A.forEach(l => push({
        id: `letters/${l.id}`, type: "letter", tier: 1,
        arabic: l.isolated, translit: l.translit, english: `letter “${l.translit}” (isolated form)`,
        category: "alphabet", source: "arabicAlphabet", sourceId: l.id,
        file: `letters/${l.id}.mp3`, nativeTarget: true,
    }));
    A.forEach(l => push({
        id: `names/${l.id}`, type: "letter-name", tier: 1,
        arabic: l.name, translit: l.translit, english: `name of the letter “${l.translit}”`,
        category: "alphabet", source: "arabicAlphabet", sourceId: l.id,
        file: `names/${l.id}.mp3`, nativeTarget: true,
    }));

    // 3.2 vowel-mark demo syllables (harakāt + tanwīn) — Tier 1
    data.HARAKAT.forEach(h => push({
        id: `marks/${h.id}`, type: "mark", tier: 1,
        arabic: h.symbolWord, translit: h.translit, english: `${h.name} on a carrier letter`,
        category: "harakat", source: "HARAKAT", sourceId: h.id,
        file: `marks/${h.id}.mp3`, nativeTarget: true,
    }));
    data.TANWIN.forEach(t => push({
        id: `marks/${t.id}`, type: "mark", tier: 1,
        arabic: t.symbolWord, translit: t.translit, english: `${t.name} on a carrier letter`,
        category: "harakat", source: "TANWIN", sourceId: t.id,
        file: `marks/${t.id}.mp3`, nativeTarget: true,
    }));

    // 3.3 syllables: CVV / CVC / geminated — Tier 1
    [["cvvSyllables", data.cvvSyllables], ["cvcSyllables", data.cvcSyllables], ["geminatedSyllables", data.geminatedSyllables]]
        .forEach(([src, arr]) => arr.forEach(s => push({
            id: `syllables/${s.id}`, type: "syllable", tier: 1,
            arabic: s.arabic, translit: s.transliteration, english: s.english,
            category: "syllables", source: src, sourceId: s.id,
            file: `syllables/${s.id}.mp3`, nativeTarget: true,
        })));

    // 3.4 sentences: M8 reading passages (+ M9 reduced / unvowelled aliases) — Tier 1
    data.readingPassages.forEach(p => {
        push({
            id: `sentences/${p.id}`, type: "sentence", tier: 1,
            arabic: p.sentence, translit: p.transliteration, english: p.meaning,
            category: "reading", source: "readingPassages", sourceId: p.id,
            file: `sentences/${p.id}.mp3`, nativeTarget: true,
        });
        // M9 derived forms — read the same sentence with fewer marks; the
        // correct pronunciation is identical, so they alias the base recording.
        if (p.reduced && normalizeArabic(p.reduced) !== normalizeArabic(p.sentence)) push({
            id: `sentences/${p.id}~reduced`, type: "sentence", tier: 1,
            arabic: p.reduced, translit: p.transliteration, english: p.meaning,
            category: "reading", source: "readingPassages.reduced", sourceId: p.id,
            aliasOf: `sentences/${p.id}`,
        });
        if (p.unvowelled && normalizeArabic(p.unvowelled) !== normalizeArabic(p.reduced)) push({
            id: `sentences/${p.id}~unvowelled`, type: "sentence", tier: 1,
            arabic: p.unvowelled, translit: p.transliteration, english: p.meaning,
            category: "reading", source: "readingPassages.unvowelled", sourceId: p.id,
            aliasOf: `sentences/${p.id}`,
        });
    });

    // 3.5 sentences: M11 grammar examples — Tier 1
    data.grammarExamples.forEach(g => push({
        id: `sentences/${g.id}`, type: "sentence", tier: 1,
        arabic: g.sentence, translit: g.transliteration, english: g.meaning,
        category: "grammar", source: "grammarExamples", sourceId: g.id,
        file: `sentences/${g.id}.mp3`, nativeTarget: true,
    }));

    // 3.6 vocabulary headwords — Tier 2
    data.vocabulary.forEach(w => push({
        id: `words/${w.id}`, type: "word", tier: 2,
        arabic: w.arabic, translit: w.translit, english: w.english,
        category: w.category, source: "vocabulary", sourceId: w.id,
        file: `words/${w.id}.mp3`, nativeTarget: true,
    }));

    // 3.7 vocabulary plurals — Tier 2
    data.vocabulary.filter(w => w.plural).forEach(w => push({
        id: `words/${w.id}-pl`, type: "word-plural", tier: 2,
        arabic: w.plural.arabic, translit: w.plural.translit, english: `${w.english} (plural)`,
        category: w.category, source: "vocabulary.plural", sourceId: w.id,
        file: `words/${w.id}-pl.mp3`, nativeTarget: true,
    }));

    // 3.8 vocabulary example sentences — Tier 2
    data.vocabulary.filter(w => w.example).forEach(w => push({
        id: `sentences/${w.id}-ex`, type: "sentence", tier: 2,
        arabic: w.example.arabic, translit: "", english: w.example.english,
        category: w.category, source: "vocabulary.example", sourceId: w.id,
        file: `sentences/${w.id}-ex.mp3`, nativeTarget: true,
    }));

    // 3.9  (removed in M14) — the legacy `flashcards` deck was unified into the
    //      Word Bank; every one of its 46 words is now a `vocabulary` lexeme and
    //      is already covered by §3.6 above.

    // 3.10 Tier 3 — the generated consonant × harakah grid used by the M6
    //      "every letter with fatḥah / kasrah / ḍammah" reading steps.
    //      Decision (M13): these stay TTS. Listed so coverage is honest and so
    //      they *could* be swapped to recordings later without code changes.
    A.filter(l => l.id !== "alif").forEach(l => data.HARAKAT.forEach(h => {
        const arabic = l.isolated + h.mark;
        if (byKey.has(normalizeArabic(arabic))) return; // already a real syllable
        targets.push({
            id: `grid/${l.id}-${h.id}`, type: "syllable-grid", tier: 3,
            arabic, translit: l.translit + h.translit, english: `${l.translit} + ${h.translit}`,
            category: "syllables", source: "generated:buildFullAlphabetMarkStep", sourceId: `${l.id}+${h.id}`,
            key: normalizeArabic(arabic), role: "tts-only", file: null, nativeTarget: false,
        });
    }));

    // stable order: tier, then type, then id
    targets.sort((a, b) =>
        a.tier - b.tier ||
        a.type.localeCompare(b.type) ||
        a.id.localeCompare(b.id));

    return targets;
}

/* -------------------------------------------------------------------------- */
/* 4. Decorate with on-disk presence + playback status                       */
/* -------------------------------------------------------------------------- */
function decorate(targets) {
    const present = new Set();
    if (fs.existsSync(AUDIO_DIR)) {
        for (const entry of walk(AUDIO_DIR)) {
            present.add(path.relative(AUDIO_DIR, entry).split(path.sep).join("/"));
        }
    }
    return targets.map(t => {
        const file = t.file || (t.aliasOf ? aliasFile(targets, t.aliasOf) : null);
        const hasFile = file ? present.has(file) : false;
        return {
            id: t.id,
            type: t.type,
            tier: t.tier,
            role: t.role,                                  // "recording" | "alias" | "tts-only"
            arabic: t.arabic,
            translit: t.translit,
            english: t.english,
            category: t.category,
            source: t.source,
            sourceId: t.sourceId,
            file: file ? `audio/${file}` : null,
            aliasOf: t.aliasOf || null,
            nativeTarget: !!t.nativeTarget,
            filePresent: hasFile,
            playback: hasFile ? "native" : "tts",          // what the app will actually do
        };
    });
}
function aliasFile(targets, id) { const o = targets.find(x => x.id === id); return o ? o.file : null; }
function* walk(dir) {
    for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, d.name);
        if (d.isDirectory()) yield* walk(p);
        else if (/\.(mp3|m4a|ogg|wav)$/i.test(d.name)) yield p;
    }
}

