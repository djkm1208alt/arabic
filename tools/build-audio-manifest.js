#!/usr/bin/env node
/* =============================================================================
   build-audio-manifest.js  —  M13 audio preparation tooling
   =============================================================================

   DEVELOPMENT / BUILD-TIME TOOL. Not required by the browser at runtime and
   never fetched by the app. Node built-ins only, zero dependencies.

   Purpose
   -------
   The Arabic learning app plays ~360 distinct Arabic strings (letters, letter
   names, vowel-mark syllables, syllables, words, and sentences). Today every
   one of them is spoken by the browser's speech-synthesis engine (TTS) — there
   are no recorded audio files in this repo.

   This tool builds a deterministic inventory of those audio targets straight
   from the app's own data (index.html), so that:
     * we have a trustworthy, always-current picture of audio coverage, and
     * professionally recorded native-speaker audio can later be dropped in as
       an asset + one-flag change, with no rewrite of the learning system.

   It does NOT generate, synthesize, or fabricate any audio. It only inventories
   what the app already references and reports which files are present on disk.

   Usage
   -----
     node tools/build-audio-manifest.js
         Regenerate tools/audio-manifest.json and tools/audio-manifest.md and
         print a coverage summary.

     node tools/build-audio-manifest.js --check
         Regenerate in memory and compare to the committed files. Exit 1 if they
         differ (use in CI / pre-commit). No files written.

     node tools/build-audio-manifest.js --write-app
         Also refresh the RECORDED_AUDIO_MANIFEST block inside index.html
         (between its AUTO-GENERATED marker comments). Use after adding
         vocabulary so the in-app lookup table stays in sync.

   Running it twice with no source change produces byte-identical output.
   ============================================================================= */

