function extractAppBlock(html) {
    const i = html.indexOf(APP_MARKER_START);
    const j = html.indexOf(APP_MARKER_END);
    if (i === -1 || j === -1) return null;
    return html.slice(i, j + APP_MARKER_END.length);
}
function replaceAppBlock(html, block) {
    const cur = extractAppBlock(html);
    if (cur === null) throw new Error("RECORDED_AUDIO_MANIFEST markers not found in index.html — add them once, then rerun --write-app");
    return html.replace(cur, block);
}

