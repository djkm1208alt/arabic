// M20's linguistic linter is a separate pure module; alias it so it doesn't
// collide with this file's own advisory `lint()` (M14.5 + M20.5).
const { lint: linguisticLint } = require("./content-lint.js");

function main() {
    const args = new Set(process.argv.slice(2));
    const { errors, data, legacyMap } = load();

    if (errors.length) {
        console.error("content validation FAILED:");
        errors.forEach(e => console.error("  - " + e));
        process.exit(1);
    }

    /* M20 — linguistic lint. HARD errors block every run (a colloquialism in
       MSA content, an Arabic-Indic digit outside the numbers topic, a
       translit/script emphatic mismatch are never acceptable). Its WARNINGS
       are advisory and only surface under --lint, alongside M14.5/M20.5. */
    const ling = linguisticLint(data, data._wordlists, data._lintAllow);
    if (ling.errors.length) {
        console.error("linguistic lint FAILED:");
        ling.errors.forEach(e => console.error("  - " + e));
        process.exit(1);
    }

    if (args.has("--lint")) {
        const warnings = [
            ...ling.warnings.map(w => "linguistic — " + w),
            ...lint(data, legacyMap),
        ];
        if (warnings.length) {
            console.log(`content lint — ${warnings.length} advisory warning(s):`);
            warnings.forEach(w => console.log("  ! " + w));
        } else {
            console.log("content lint — clean, no advisory warnings.");
        }
        return;
    }

    const counts = Object.fromEntries(Object.keys(FILES).map(k => [k, data[k].length]));
    const block = compile(data, legacyMap);
    const html = fs.readFileSync(INDEX_HTML, "utf8");
    const current = extractBlock(html);

    if (args.has("--check")) {
        if (current === null) { console.error("--check: CONTENT markers not found in index.html"); process.exit(1); }
        if (lf(current) !== lf(block)) {
            console.error("STALE — index.html CONTENT block is out of date. Run: node tools/build-content.js --write-app");
            process.exit(1);
        }
        console.log(`content OK and index.html in sync — ${sum(counts)} objects (${describe(counts)}).`);
        return;
    }

    if (args.has("--write-app")) {
        if (current === null) {
            console.error("\n--write-app: CONTENT markers not found in index.html. Add this once, in the DATA section:\n");
            console.error(MARKER_START + "\nconst CONTENT = {};\n" + MARKER_END + "\n");
            process.exit(2);
        }
        const eol = html.includes("\r\n") ? "\r\n" : "\n";
        const updated = html.replace(current, block.replace(/\n/g, eol));
        if (lf(updated) === lf(html)) console.log("index.html CONTENT block already current.");
        else { fs.writeFileSync(INDEX_HTML, updated); console.log("updated index.html CONTENT block."); }
    }

    console.log("");
    console.log("content validated — " + sum(counts) + " learning objects");
    for (const [k, n] of Object.entries(counts)) console.log("  " + k.padEnd(12) + n);
    console.log("  legacy id map  " + Object.keys(legacyMap).length);
    console.log("  taxonomy       " + (data.skills || []).length + " skills, " + (data.levels || []).length + " levels, " + (data.descriptors || []).length + " descriptors");
    if (data.curriculum) console.log("  curriculum     " + data.curriculum.units.length + " units, " + data.curriculum.lessons.length + " lessons");
    console.log("  lessons (data) " + (data.lessons || []).length);
    if (!args.has("--write-app")) console.log("\n(run with --write-app to splice into index.html, or --check to verify)");
}

function sum(c) { return Object.values(c).reduce((a, b) => a + b, 0); }
function describe(c) { return Object.entries(c).map(([k, n]) => `${n} ${k}`).join(", "); }

main();
