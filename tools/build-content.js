function compile(data, legacyMap) {
    // Source-file order is preserved verbatim — it is semantically meaningful
    // (letters run alif→yāʾ, harakāt fatḥah→ḍammah, reading passages in lesson
    // order, …). Deterministic because the JSON files are the source of truth.
    const section = (key) => {
        const rows = data[key].map(o => "  " + JSON.stringify(o) + ",");
        return `"${key}": [\n${rows.join("\n")}\n]`;
    };
    // curriculum is an object { levels, units, lessons }; emit each as a row list.
    const curriculumBlock = () => {
        const arr = (name) => {
            const rows = (data.curriculum[name] || []).map(o => "    " + JSON.stringify(o) + ",");
            return `  "${name}": [\n${rows.join("\n")}\n  ]`;
        };
        return `"curriculum": {\n${[arr("levels"), arr("units"), arr("lessons")].join(",\n")}\n}`;
    };
    const mapRows = Object.keys(legacyMap)
        .sort((a, b) => Number(a) - Number(b))
        .map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(legacyMap[k])},`);

    // M20 — lessons authored as data. `fromObjectives` steps are expanded here
    // from the referenced objects, so no Arabic is inlined in the lesson file.
    const compiledLessons = (data.lessons || []).map(L => {
        const obj = id => data._objById && data._objById.get(id);
        const steps = (L.steps || []).map(s => {
            if ((s.type === "example-set" || s.type === "reading-practice") && s.fromObjectives) {
                const lex = (L.objectives || []).map(obj).filter(o => o && o.kind === "lexeme");
                const out = Object.assign({}, s); delete out.fromObjectives;
                if (s.type === "example-set") out.items = lex.map(l => ({ symbolWord: l.ar, name: l.en, translit: l.translit, sound: l.pos || "", examples: [] }));
                else out.items = lex.map(l => ({ arabic: l.ar, translit: l.translit, english: l.en }));
                return out;
            }
            return s;
        });
        return { id: L.id, title: L.title, curriculumLessonId: L.curriculumLessonId || null, objectives: L.objectives || [], steps };
    });

    return [
        MARKER_START,
        "/* Learning-object content, compiled from content/*.json by",
        "   tools/build-content.js. Do not hand-edit. Regenerate:",
        "     node tools/build-content.js --write-app */",
        "const CONTENT = {",
        section("skills") + ",",
        section("levels") + ",",
        section("descriptors") + ",",
        section("lexemes") + ",",
        section("letters") + ",",
        section("marks") + ",",
        section("syllables") + ",",
        section("grammar") + ",",
        section("texts") + ",",
        curriculumBlock() + ",",
        `"lessons": [\n${compiledLessons.map(o => "  " + JSON.stringify(o) + ",").join("\n")}\n]` + ",",
        `"legacyFlashcardId": {\n${mapRows.join("\n")}\n}`,
        "};",
        MARKER_END,
    ].join("\n");
}

function extractBlock(html) {
    const i = html.indexOf(MARKER_START);
    const j = html.indexOf(MARKER_END);
    if (i === -1 || j === -1) return null;
    return html.slice(i, j + MARKER_END.length);
}

